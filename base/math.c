double base_floor(double x) {
    if (x >= 4503599627370496.0 || x <= -4503599627370496.0 || x != x) return x;
    int64_t i = (int64_t)x;
    double d = (double)i;
    return (d > x) ? (d - 1.0) : d;
}

float base_floorf(float x) {
    if (x >= 8388608.0f || x <= -8388608.0f || x != x) return x;
    int32_t i = (int32_t)x;
    float f = (float)i;
    return (f > x) ? (f - 1.0f) : f;
}

double base_ceil(double x) {
    if (x >= 4503599627370496.0 || x <= -4503599627370496.0 || x != x) return x;
    int64_t i = (int64_t)x;
    double d = (double)i;
    return (d < x) ? (d + 1.0) : d;
}

float base_ceilf(float x) {
    if (x >= 8388608.0f || x <= -8388608.0f || x != x) return x;
    int32_t i = (int32_t)x;
    float f = (float)i;
    return (f < x) ? (f + 1.0f) : f;
}

double base_fmod(double x, double y) {
    if (y == 0.0 || x != x || y != y) return (double)NAN;
    double ay = y < 0.0 ? -y : y;
    double q = x / ay;
    double iq = (q >= 0.0) ? base_floor(q) : base_ceil(q);
    return x - iq * ay;
}

float base_fmodf(float x, float y) {
    if (y == 0.0f || x != x || y != y) return NAN;
    float ay = y < 0.0f ? -y : y;
    float q = x / ay;
    float iq = (q >= 0.0f) ? base_floorf(q) : base_ceilf(q);
    return x - iq * ay;
}

// -----------------------------------------------------------------------------
// Double-precision trig: fast_sin, fast_cos, fast_tan
// -----------------------------------------------------------------------------

static inline double sin_poly_d(double r) {
    double r2 = r * r;
    double r4 = r2 * r2;
    double r8 = r4 * r4;
    double p0 = -1.66666666666666657415e-01 + r2 *  8.33333333333333321769e-03;
    double p1 = -1.98412698412698412525e-04 + r2 *  2.75573192239858925126e-06;
    double p2 = -2.50521083854417202248e-08 + r2 *  1.60590438368216133407e-10;
    double p3 = -7.64716373181981641472e-13;
    return r + r * r2 * ((p0 + r4 * p1) + r8 * (p2 + r4 * p3));
}

static inline double cos_poly_d(double r) {
    double r2 = r * r;
    double r4 = r2 * r2;
    double r8 = r4 * r4;
    double p0 =  4.16666666666666643537e-02 + r2 * -1.38888888888888894189e-03;
    double p1 =  2.48015873015873015657e-05 + r2 * -2.75573192239858882757e-07;
    double p2 =  2.08767569878681001874e-09 + r2 * -1.14707455977297245224e-11;
    double p3 =  4.77947733238738525433e-14;
    return (1.0 - 0.5 * r2) + r4 * ((p0 + r4 * p1) + r8 * (p2 + r4 * p3));
}

double fast_sin(double x) {
    union { double d; uint64_t u; } ru;
    ru.d = x * INV_PI2_D + 6755399441055744.0;
    uint64_t q = ru.u;
    double kd = ru.d - 6755399441055744.0;
    double r = ((x - kd * PI2_HI) - kd * PI2_MID) - kd * PI2_LO;
    double res = (q & 1ULL) ? cos_poly_d(r) : sin_poly_d(r);
    union { double d; uint64_t u; } out;
    out.d = res;
    out.u ^= (q & 2ULL) << 62;
    return out.d;
}

double fast_cos(double x) {
    union { double d; uint64_t u; } ru;
    ru.d = x * INV_PI2_D + 6755399441055744.0;
    uint64_t q = ru.u + 1ULL;
    double kd = ru.d - 6755399441055744.0;
    double r = ((x - kd * PI2_HI) - kd * PI2_MID) - kd * PI2_LO;
    double res = (q & 1ULL) ? cos_poly_d(r) : sin_poly_d(r);
    union { double d; uint64_t u; } out;
    out.d = res;
    out.u ^= (q & 2ULL) << 62;
    return out.d;
}

double fast_tan(double x) {
    union { double d; uint64_t u; } ru;
    ru.d = x * INV_PI2_D + 6755399441055744.0;
    uint64_t q = ru.u;
    double kd = ru.d - 6755399441055744.0;
    double r = ((x - kd * PI2_HI) - kd * PI2_MID) - kd * PI2_LO;
    double s = sin_poly_d(r);
    double c = cos_poly_d(r);
    return (q & 1ULL) ? (-c / s) : (s / c);
}

// -----------------------------------------------------------------------------
// Single-precision trig: fast_sinf, fast_cosf, fast_tanf
// Range reduction by pi + single degree-9 odd minimax polynomial (zero branches)
// -----------------------------------------------------------------------------

static inline float sin_pi_reduced_f(double xd) {
    union { double d; uint64_t u; } ru;
    ru.d = xd * INV_PI_D + 6755399441055744.0;
    uint64_t sign_bit = ru.u << 63;
    double kd = ru.d - 6755399441055744.0;
    double r = xd - kd * PI_D; // r in [-pi/2, pi/2]
    double r2 = r * r;
    double r4 = r2 * r2;
    double p0 = -1.66666659638213061e-01 + r2 * 8.33324213509949695e-03;
    double p1 = -1.98227394888014145e-04 + r2 * 2.63475639216362554e-06;
    double res = r + (r * r2) * (p0 + r4 * p1);
    union { double d; uint64_t u; } out;
    out.d = res;
    out.u ^= sign_bit;
    return (float)out.d;
}

float fast_sinf(float x) {
    return sin_pi_reduced_f((double)x);
}

float fast_cosf(float x) {
    return sin_pi_reduced_f((double)x + PI2_D);
}

float fast_tanf(float x) {
    double xd = (double)x;
    union { double d; uint64_t u; } ru;
    ru.d = xd * INV_PI2_D + 6755399441055744.0;
    uint64_t q = ru.u;
    double kd = ru.d - 6755399441055744.0;
    double r = xd - kd * PI2_D;
    double r2 = r * r;
    double r4 = r2 * r2;
    double s = r + r * r2 * ((-1.6666666666666666e-01 + r2 * 8.3333333333333332e-03) +
                             r4 * (-1.9841269841269841e-04 + r2 * 2.7557319223985893e-06));
    double c = (1.0 - 0.5 * r2) + r4 * ((4.1666666666666664e-02 + r2 * -1.3888888888888889e-03) +
                                         r4 * 2.4801587301587302e-05);
    return (float)((q & 1ULL) ? (-c / s) : (s / c));
}

// -----------------------------------------------------------------------------
// Exponential: fast_exp, fast_expf (64-entry table, single range check)
// -----------------------------------------------------------------------------

static inline double exp_poly5_d(double r) {
    double r2 = r * r;
    double r4 = r2 * r2;
    double p0 = 1.0 + r;
    double p1 = 0.5 + r * 1.66666666666666657415e-01;
    double p2 = 4.16666666666666643537e-02 + r * 8.33333333333333321769e-03;
    return (p0 + r2 * p1) + r4 * p2;
}

static double exp_special_d(double x) {
    if (x > 709.782712893384) return (double)INFINITY;
    if (x < -745.1332191019412) return 0.0;
    if (x != x) return (double)NAN;
    union { double d; uint64_t u; } ru;
    ru.d = x * INV_LN2_64 + 6755399441055744.0;
    int64_t n = (int64_t)(int32_t)ru.u;
    double nd = ru.d - 6755399441055744.0;
    double r = (x - nd * LN2_64_HI) - nd * LN2_64_LO;
    double poly = exp_poly5_d(r);
    int64_t k = n >> 6;
    int64_t k1 = k / 2;
    int64_t k2 = k - k1;
    union { double d; uint64_t u; } s1;
    union { double d; uint64_t u; } s2;
    s1.u = EXP2_D_BITS[n & 63] + ((uint64_t)k1 << 52);
    s2.u = (uint64_t)(k2 + 1023) << 52;
    return (poly * s1.d) * s2.d;
}

double fast_exp(double x) {
    union { double d; uint64_t u; } xu;
    xu.d = x;
    if ((xu.u & 0x7FFFFFFFFFFFFFFFULL) >= 0x4086200000000000ULL) return exp_special_d(x);
    union { double d; uint64_t u; } ru;
    ru.d = x * INV_LN2_64 + 6755399441055744.0;
    int64_t n = (int64_t)(int32_t)ru.u;
    double nd = ru.d - 6755399441055744.0;
    double r = (x - nd * LN2_64_HI) - nd * LN2_64_LO;
    union { double d; uint64_t u; } s;
    s.u = EXP2_D_BITS[n & 63] + ((uint64_t)(n >> 6) << 52);
    return exp_poly5_d(r) * s.d;
}

float fast_expf(float x) {
    union { float f; uint32_t u; } xu;
    xu.f = x;
    // Fast path: |x| < 104.0f (0x42D00000U) — double handles all float32 subnormals/overflow!
    if ((xu.u & 0x7FFFFFFFU) >= 0x42D00000U) {
        if (x > 0.0f) return INFINITY;
        if (x != x) return NAN;
        return 0.0f;
    }
    double xd = (double)x;
    union { double d; uint64_t u; } ru;
    ru.d = xd * INV_LN2_64 + 6755399441055744.0;
    int64_t n = (int64_t)(int32_t)ru.u;
    double nd = ru.d - 6755399441055744.0;
    double r = xd - nd * LN2_64_D;
    // |r| <= 0.005415 -> degree-2 error = |r|^3/6 = 2.6e-8 (< 0.25 ULP of float32!)
    double poly = 1.0 + r * (1.0 + r * 0.5);
    union { double d; uint64_t u; } s;
    s.u = EXP2_D_BITS[n & 63] + ((uint64_t)(n >> 6) << 52);
    return (float)(poly * s.d);
}

// -----------------------------------------------------------------------------
// Natural logarithm: fast_log, fast_logf (128-entry interleaved table, 0 divs)
// -----------------------------------------------------------------------------

static inline double log1p_poly6_d(double u) {
    // With 128-entry table, |u| <= 0.015 -> |u|^8/8 < 3.2e-16
    double u2 = u * u;
    double u4 = u2 * u2;
    double p0 =  1.0                        + u * -0.5;
    double p1 =  3.33333333333333314830e-01 + u * -0.25;
    double p2 =  2.00000000000000011102e-01 + u * -1.66666666666666657415e-01;
    double p3 =  1.42857142857142849213e-01;
    return u * ((p0 + u2 * p1) + u4 * (p2 + u2 * p3));
}

double fast_log(double x) {
    if (x <= 0.0) return (x == 0.0) ? -(double)INFINITY : (double)NAN;
    union { double d; uint64_t u; } b;
    b.d = x;
    uint64_t tmp = b.u - 0x3FE6A09E667F3BCDULL;
    int64_t e = (int64_t)tmp >> 52;
    uint64_t frac = tmp & 0x000FFFFFFFFFFFFFULL;
    uint64_t idx = frac >> 45;
    b.u = frac + 0x3FE6A09E667F3BCDULL;
    double u = b.d * LOG_TAB[idx].inv - 1.0;
    double ed = (double)e;
    return (ed * LN2_HI + LOG_TAB[idx].ln_c) + (ed * LN2_LO + log1p_poly6_d(u));
}

float fast_logf(float x) {
    if (x <= 0.0f) return (x == 0.0f) ? -INFINITY : NAN;
    union { float f; uint32_t u; } b;
    b.f = x;
    uint32_t tmp = b.u - 0x3F3504F3U;
    int32_t e = (int32_t)tmp >> 23;
    uint32_t frac = tmp & 0x007FFFFFU;
    uint32_t idx = frac >> 16;
    b.u = frac + 0x3F3504F3U;
    double u = (double)b.f * LOG_TAB[idx].inv - 1.0;
    double lp = u * (1.0 + u * (-0.5 + u * 3.3333333333333331e-01));
    return (float)((double)e * 0.6931471805599453 + LOG_TAB[idx].ln_c + lp);
}

// -----------------------------------------------------------------------------
// Power: fast_pow, fast_powf (128-entry log2 + 64-entry exp2, 0 divisions)
// -----------------------------------------------------------------------------

static double pow_special_d(double x, double y) {
    if (y == 0.0) return 1.0;
    if (x == 0.0) return (y > 0.0) ? 0.0 : (double)INFINITY;
    double iy = base_floor(y);
    if (iy != y) return (double)NAN;
    double res = fast_pow(-x, y);
    return ((int64_t)iy & 1) ? -res : res;
}

double fast_pow(double x, double y) {
    if (x <= 0.0) return pow_special_d(x, y);

    union { double d; uint64_t u; } b;
    b.d = x;
    uint64_t tmp = b.u - 0x3FE6A09E667F3BCDULL;
    int64_t e = (int64_t)tmp >> 52;
    uint64_t frac = tmp & 0x000FFFFFFFFFFFFFULL;
    uint64_t idx = frac >> 45;
    b.u = frac + 0x3FE6A09E667F3BCDULL;

    double u = b.d * LOG_TAB[idx].inv - 1.0;
    double l_poly = log1p_poly6_d(u) * INV_LN2;
    double l_hi = (double)e + LOG_TAB[idx].log2_hi;
    double l_lo = LOG_TAB[idx].log2_lo + l_poly;

    double y_hi = (double)(float)y;
    double y_lo = y - y_hi;

    double p_hi = y_hi * l_hi;
    double p_lo = y_hi * l_lo + y_lo * (l_hi + l_lo);
    double p_tot = p_hi + p_lo;

    union { double d; uint64_t u; } pu;
    pu.d = p_tot;
    if ((pu.u & 0x7FFFFFFFFFFFFFFFULL) >= 0x408FF00000000000ULL) {
        if (p_tot >= 1024.0) return (double)INFINITY;
        if (p_tot < -1075.0) return 0.0;
        return exp_special_d(p_tot * LN2_HI + p_tot * LN2_LO);
    }

    union { double d; uint64_t u; } ru;
    ru.d = p_tot * 64.0 + 6755399441055744.0;
    int64_t n = (int64_t)(int32_t)ru.u;
    double nd = (ru.d - 6755399441055744.0) * 0.015625;
    double f = (p_hi - nd) + p_lo;
    double r = f * LN2_HI + f * LN2_LO;
    union { double d; uint64_t u; } s;
    s.u = EXP2_D_BITS[n & 63] + ((uint64_t)(n >> 6) << 52);
    return exp_poly5_d(r) * s.d;
}

static float pow_special_f(float x, float y) {
    if (y == 0.0f) return 1.0f;
    if (x == 0.0f) return (y > 0.0f) ? 0.0f : INFINITY;
    float iy = base_floorf(y);
    if (iy != y) return NAN;
    float res = fast_powf(-x, y);
    return ((int32_t)iy & 1) ? -res : res;
}

float fast_powf(float x, float y) {
    if (x <= 0.0f) return pow_special_f(x, y);

    union { float f; uint32_t u; } b;
    b.f = x;
    uint32_t tmp = b.u - 0x3F3504F3U;
    int32_t e = (int32_t)tmp >> 23;
    uint32_t frac = tmp & 0x007FFFFFU;
    uint32_t idx = frac >> 16;
    b.u = frac + 0x3F3504F3U;

    double u = (double)b.f * LOG_TAB[idx].inv - 1.0;
    // Pre-multiplied by 1/ln(2) to remove a dependent multiply from the critical path
    double l_poly = u * (1.4426950408889634 + u * (-0.7213475204444817 + u * 0.4808983469629878));
    double log2_x = ((double)e + LOG_TAB[idx].log2_hi) + (LOG_TAB[idx].log2_lo + l_poly);
    double p = (double)y * log2_x;

    union { double d; uint64_t u; } pu;
    pu.d = p;
    if ((pu.u & 0x7FFFFFFFFFFFFFFFULL) >= 0x4064000000000000ULL) {
        return (p > 0.0) ? INFINITY : 0.0f;
    }

    union { double d; uint64_t u; } ru;
    ru.d = p * 64.0 + 6755399441055744.0;
    int64_t n = (int64_t)(int32_t)ru.u;
    double nd = (ru.d - 6755399441055744.0) * 0.015625;
    double f = p - nd;
    // 2^f = 1 + f*ln(2) + f^2*(ln(2)^2 / 2) — removes multiply by ln(2)
    double poly = 1.0 + f * (0.6931471805599453 + f * 0.2402265069591007);
    union { double d; uint64_t u; } s;
    s.u = EXP2_D_BITS[n & 63] + ((uint64_t)(n >> 6) << 52);
    return (float)(poly * s.d);
}

